import assert from 'node:assert/strict'
import {chromium} from 'playwright'
import {mkdir} from 'node:fs/promises'

const base=process.env.SITE_URL||'http://127.0.0.1:3000'
const locales=[{code:'fi',prefix:''},{code:'en',prefix:'/en'},{code:'sv',prefix:'/sv'}]
await mkdir('site-preview',{recursive:true})
const browser=await chromium.launch({headless:true,args:['--no-sandbox']})
try{
  for(const locale of locales){
    const page=await browser.newPage({viewport:{width:1280,height:920},reducedMotion:'reduce'})
    let response=await page.goto(base+locale.prefix+'/services',{waitUntil:'domcontentloaded'})
    assert.equal(response?.status(),200,locale.code+' services route')
    assert.equal(await page.locator('html').getAttribute('lang'),locale.code)
    assert.equal(await page.locator('.bs-package').count(),6,locale.code+' six buyer packages')
    assert.equal(await page.locator('.bs-task').count(),8,locale.code+' concise initial catalogue')
    await page.locator('.bs-expand-row button').click()
    assert.equal(await page.locator('.bs-task').count(),27,locale.code+' all twenty-seven offerings')
    assert.equal(await page.locator('.bs-tool-group').count(),2)
    await page.locator('.bs-search input').fill('Power BI')
    const count=await page.locator('.bs-task').count()
    assert.ok(count>0&&count<27,locale.code+' search narrows offerings')
    await page.locator('.bs-search input').fill('')
    assert.equal(await page.locator('.bs-task').count(),27)
    await page.locator('.bs-areas button').nth(2).click()
    assert.ok(await page.locator('.bs-task').count()<27,locale.code+' area filter')
    await page.locator('.bs-areas button').first().click()
    assert.equal(await page.locator('.bs-task').count(),27)
    response=await page.goto(base+locale.prefix+'/work',{waitUntil:'domcontentloaded'})
    assert.equal(response?.status(),200,locale.code+' work route')
    assert.equal(await page.locator('.bs-demo-tabs [role="tab"]').count(),3)
    assert.equal(await page.locator('.bs-kpis > div').count(),3)
    const before=await page.locator('.bs-kpis strong').first().innerText()
    await page.locator('.bs-demo-control select').selectOption('2024')
    assert.notEqual(await page.locator('.bs-kpis strong').first().innerText(),before,locale.code+' year filter updates KPI')
    await page.locator('.bs-demo-tabs button').nth(1).click()
    assert.equal(await page.locator('.bs-intranet-list button').count(),4,locale.code+' intranet docs')
    await page.locator('.bs-intranet-list select').selectOption('hr')
    assert.equal(await page.locator('.bs-intranet-list button').count(),1)
    await page.locator('.bs-intranet-list input').fill('NoMatch12345')
    assert.equal(await page.locator('.bs-intranet-list button').count(),0)
    await page.locator('.bs-intranet-list input').fill('')
    assert.equal(await page.locator('.bs-intranet-content ol li').count(),3)
    await page.locator('.bs-demo-tabs button').nth(2).click()
    assert.equal(await page.locator('.bs-request').count(),3)
    await page.locator('.bs-workflow-compose button').click()
    assert.equal(await page.locator('.bs-request').count(),4)
    await page.locator('.bs-request-actions button').first().click()
    assert.equal(await page.locator('.bs-request').count(),4)
    assert.ok(await page.locator('.bs-request-status.bs-approved').count()>=2)
    await page.locator('.bs-workflow-footer button').click()
    assert.equal(await page.locator('.bs-request').count(),3)
    await page.locator('.bs-demo-tabs button').first().focus()
    await page.keyboard.press('ArrowRight')
    assert.equal(await page.locator('.bs-demo-tabs button[aria-selected="true"]').count(),1)
    assert.equal(await page.locator('.bs-demo-tabs button[aria-selected="true"]').getAttribute('id'),'bs-tab-intranet')
    await page.setViewportSize({width:390,height:850})
    await page.goto(base+locale.prefix+'/work',{waitUntil:'domcontentloaded'})
    const workOverflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)
    assert.ok(workOverflow<=4,locale.code+' work mobile overflow: '+workOverflow)
    await page.screenshot({path:'site-preview/business-ops-'+locale.code+'-work-mobile.png',animations:'disabled',fullPage:true})
    await page.goto(base+locale.prefix+'/services',{waitUntil:'domcontentloaded'})
    const servicesOverflow=await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)
    assert.ok(servicesOverflow<=4,locale.code+' services mobile overflow: '+servicesOverflow)
    await page.screenshot({path:'site-preview/business-ops-'+locale.code+'-services-mobile.png',animations:'disabled',fullPage:true})
    await page.close()
  }
  console.log('PASS: twenty-seven searchable offers, six packages, funding KPIs, intranet, approval workflow, mobile and FI/EN/SV demos')
}finally{await browser.close()}
