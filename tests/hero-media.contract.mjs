import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const base=process.env.SITE_URL||'http://127.0.0.1:3000'
const browser=await chromium.launch({headless:true,args:['--no-sandbox']})
try{
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'})
  const page=await mobile.newPage()
  await page.goto(base+'/',{waitUntil:'domcontentloaded'})
  await page.waitForTimeout(600)
  assert.equal(await page.locator('.kc-hero-video source').count(),0,'Reduced motion must not fetch video before opt-in')
  await page.locator('.kc-hero-poster').evaluate(img=>img.decode())
  const mobilePoster=await page.locator('.kc-hero-poster').evaluate(img=>img.currentSrc)
  assert.match(mobilePoster,/hero-mobile\.webp$/,'Mobile must load small poster rather than original 300KB poster')
  const sourceOrder=await page.locator('.kc-hero').evaluate(section=>[...section.children].map(node=>node.className))
  assert.ok(sourceOrder.findIndex(cls=>cls.includes('kc-hero-layout'))<sourceOrder.findIndex(cls=>cls.includes('qh-film-layer')),'Hero DOM must present text before film; CSS-only order can shift on cold load')
  const copy=await page.locator('.kc-hero-layout').boundingBox()
  const film=await page.locator('.qh-film-layer').boundingBox()
  assert.ok(copy&&film,'Hero copy and film should have dimensions')
  assert.ok(film.y>=copy.y+copy.height-2,'Mobile film must follow solid copy panel')
  assert.ok(Math.abs(film.width/film.height-1.6)<0.08,'Mobile film should have 16:10 aspect ratio')
  await page.getByRole('button',{name:/Toista taustavideo/}).click()
  await page.waitForFunction(()=>{const v=document.querySelector('.kc-hero-video');return v&&v.currentTime>.25},null,{timeout:10000})
  assert.equal(await page.locator('.kc-hero-video source').count(),2,'Explicit Play attaches original and optimized sources')
  assert.equal(await page.locator('video.kc-hero-video').evaluate(v=>v.videoWidth),854,'Mobile must decode the sub-2MB derivative')
  await page.getByRole('button',{name:/Pysäytä taustavideo/}).click()
  assert.equal(await page.locator('video').evaluate(v=>v.paused),true,'Manual pause stops video')
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.reload({waitUntil:'domcontentloaded'})
  await page.locator('.qh-film-layer').scrollIntoViewIfNeeded()
  await page.waitForTimeout(600)
  assert.equal(await page.locator('.kc-hero-video source').count(),0,'Manual pause persists even after motion preference allows autoplay')
  await mobile.close()
  const autoCtx=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'no-preference'})
  const autoPage=await autoCtx.newPage()
  await autoPage.goto(base+'/',{waitUntil:'domcontentloaded'})
  await autoPage.waitForTimeout(650)
  const initialRatio=await autoPage.locator('.qh-film-layer').evaluate(el=>{
    const r=el.getBoundingClientRect()
    const visible=Math.max(0,Math.min(window.innerHeight,r.bottom)-Math.max(0,r.top))
    return visible/r.height
  })
  if(initialRatio<0.7)assert.equal(await autoPage.locator('.kc-hero-video source').count(),0,'Off-screen mobile film should not compete with first paint')
  await autoPage.locator('.qh-film-layer').evaluate(el=>window.scrollTo(0,window.scrollY+el.getBoundingClientRect().top-100))
  await autoPage.waitForFunction(()=>{const v=document.querySelector('.kc-hero-video');return v&&v.currentTime>.25},null,{timeout:15000})
  const fetched=await autoPage.evaluate(()=>performance.getEntriesByType('resource').map(e=>new URL(e.name).pathname))
  assert.ok(!fetched.includes('/media/hero.webp'),'Mobile should not download full-resolution poster as a CSS background')
  await autoCtx.close()
  const dataCtx=await browser.newContext({viewport:{width:1280,height:800},reducedMotion:'no-preference'})
  await dataCtx.addInitScript(()=>{Object.defineProperty(navigator,'connection',{configurable:true,value:{saveData:true}})})
  const dataPage=await dataCtx.newPage()
  await dataPage.goto(base+'/',{waitUntil:'domcontentloaded'})
  await dataPage.waitForTimeout(500)
  assert.equal(await dataPage.locator('.kc-hero-video source').count(),0,'Save-Data mode uses poster only')
  await dataCtx.close()
  const desktop=await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'no-preference'})
  const desktopPage=await desktop.newPage()
  await desktopPage.goto(base+'/',{waitUntil:'domcontentloaded'})
  await desktopPage.waitForFunction(()=>{const v=document.querySelector('.kc-hero-video');return v&&v.currentTime>.3},null,{timeout:15000})
  assert.equal(await desktopPage.locator('.kc-hero-video source').count(),2,'Desktop uses optimized source')
  assert.equal(await desktopPage.locator('video.kc-hero-video').evaluate(v=>v.videoWidth),1280,'Desktop must decode the smaller 720p derivative')
  await desktopPage.evaluate(()=>window.scrollTo(0,document.body.scrollHeight))
  await desktopPage.waitForFunction(()=>{const v=document.querySelector('.kc-hero-video');return v&&v.paused},null,{timeout:8000})
  await desktop.close()
  // Desktop browsers with reduced-motion or blocked autoplay must still let the user
  // start the original film from the visible control. This is a real click hit-test.
  const manualDesktop=await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'reduce'})
  const manualPage=await manualDesktop.newPage()
  await manualPage.goto(base+'/',{waitUntil:'domcontentloaded'})
  await manualPage.waitForTimeout(400)
  assert.equal(await manualPage.locator('.kc-hero-video source').count(),0,'Desktop reduced-motion must defer automatic film loading')
  const playButton=manualPage.getByRole('button',{name:/Toista taustavideo/})
  const hit=await playButton.evaluate(button=>{
    const r=button.getBoundingClientRect()
    const target=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2)
    return target===button||button.contains(target)
  })
  assert.equal(hit,true,'Desktop Play control must be above hero text and overlays for actual pointer clicks')
  await playButton.click()
  await manualPage.waitForFunction(()=>{
    const v=document.querySelector('.kc-hero-video')
    return v&&v.currentTime>.25&&!v.paused
  },null,{timeout:15000})
  assert.equal(await manualPage.locator('video.kc-hero-video').evaluate(v=>v.videoWidth),1280,
    'Desktop explicit Play should use the optimized 720p film')
  await manualPage.getByRole('button',{name:/Pysäytä taustavideo/}).click()
  assert.equal(await manualPage.locator('video').evaluate(v=>v.paused),true)
  await manualDesktop.close()
  console.log('Hero media PASS: mobile geometry, reduced motion, manual playback, persistent pause, data saving and offscreen pause')
}finally{await browser.close()}
